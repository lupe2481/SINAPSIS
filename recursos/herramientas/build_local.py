"""Generate the browser entry point for file:// and HTTP, using only Python stdlib."""
from pathlib import Path
import base64
import json
import re

ROOT = Path(__file__).resolve().parents[2]
source = (ROOT / 'main.js').read_text()
pattern = r"^import \{([^}]+)\} from '([^']+)';$"

def bundle_module(match):
    names, path = match.groups()
    module = (ROOT / path.split('?')[0]).read_text()
    # Each dependency keeps its private declarations in its own scope.
    module = re.sub(r'^export (?=(?:const|let|function) )', '', module, flags=re.M)
    if re.search(r'^(?:import|export) ', module, flags=re.M):
        raise ValueError('Unsupported module syntax in ' + path)
    return 'const {' + names + '} = (() => {\n' + module + '\nreturn {' + names + '};\n})();'

source = re.sub(pattern, bundle_module, source, flags=re.M)
data = json.loads((ROOT / 'recursos/data.json').read_text())
old = "try{const response=await fetch('./recursos/data.json');if(!response.ok)throw Error();data=await response.json()}catch(e){$('#loading').textContent='No se pudieron cargar los datos. Recarga la página.';throw e}"
assert old in source, 'Update the data loader transformation.'
source = source.replace(old, 'data=' + json.dumps(data, ensure_ascii=False) + ';')
svg = base64.b64encode((ROOT / 'recursos/assets/neuronal-reference.svg').read_bytes()).decode()
old = "neuralImage.src='./recursos/assets/neuronal-reference.svg'"
assert old in source, 'Update the image loader transformation.'
source = source.replace(old, "neuralImage.src='data:image/svg+xml;base64," + svg + "'")
output = '// Generated by recursos/herramientas/build_local.py. Do not edit.\n(async () => {\n' + source + "\n})().catch(error => { console.error(error); const loading=document.querySelector('#loading'); if(loading){loading.hidden=false;loading.textContent='No se pudo iniciar la experiencia. Recarga la página.';} });\n"
(ROOT / 'recursos/js/atlas.bundle.js').write_text(output)
print('Generated recursos/js/atlas.bundle.js')

import assert from 'node:assert/strict';
import {project,zoomAt,panBy,stainScore} from '../dist/view.js';
const v={x:0,y:0,scale:1},w=1280,h=630;
assert.deepEqual(project(900,300,w,h,v),{x:900,y:300});
zoomAt(v,2,900,300,w,h);
assert.deepEqual(project(900,300,w,h,v),{x:900,y:300},'cursor anchor remains fixed');
const before=project(500,200,w,h,v);panBy(v,100,50,w,h);const after=project(500,200,w,h,v);
assert.equal(after.x-before.x,100);assert.equal(after.y-before.y,50);
panBy(v,1e6,-1e6,w,h);assert.equal(v.x,0);assert.equal(v.y,-h);
zoomAt(v,.01,640,315,w,h);assert.deepEqual(v,{x:0,y:0,scale:1});
panBy(v,100,100,w,h);assert.deepEqual(v,{x:0,y:0,scale:1},'cannot pan at base scale');
zoomAt(v,1e6,640,315,w,h);assert.equal(v.scale,5);
assert.equal(stainScore(640,315,640,315,w,h),0);
console.log('PASS: flat coordinates, pointer-anchored zoom, drag translation, pan bounds, zoom limits and centered stain.');
